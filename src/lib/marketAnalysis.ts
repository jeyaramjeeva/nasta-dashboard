/** Google Maps listing copied by Jeeva. Previous = last stored snapshot (often another site), not 30-day growth. */
function gmaps(
  rating: number,
  reviewCount: number,
  query: string,
  priceRange: string,
  prev: { rating: number | null; reviews: number | null; source: string } | null = null,
  extra = '',
): RatingSnap {
  return {
    rating,
    reviewCount,
    source: GMAPS_SOURCE,
    sourceUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`,
    checkedAt: RESEARCH_CHECKED_AT,
    previousRating: prev?.rating ?? null,
    previousReviewCount: prev?.reviews ?? null,
    changeRating: prev?.rating != null ? Number((rating - prev.rating).toFixed(2)) : null,
    changeReviewCount: prev?.reviews != null ? reviewCount - prev.reviews : null,
    growth30d: null,
    growth90d: null,
    growth6m: null,
    growth12m: null,
    note: [
      `Google Maps listing copied ${RESEARCH_CHECKED_LABEL}. Maps price band: ${priceRange}. Not an API pull.`,
      '30/90/365-day growth unknown (first Google snapshot in this file).',
      prev
        ? `Prior stored figure was ${prev.source}: ${prev.rating ?? '—'} / ${prev.reviews ?? '—'}. Any delta is a source change, not period growth.`
        : '',
      extra,
    ]
      .filter(Boolean)
      .join(' '),
    confidence: 'High',
  }
}

export function vsPriorLabel(g: RatingSnap): string {
  if (g.changeReviewCount != null) {
    const sign = g.changeReviewCount > 0 ? '+' : ''
    return `${sign}${g.changeReviewCount.toLocaleString('de-DE')} vs prior stored figure`
  }
  if (g.source === GMAPS_SOURCE) return 'First Google snapshot'
  return 'Unknown'
}

export function vsPriorHint(g: RatingSnap): string {
  if (g.changeReviewCount != null) {
    return 'Delta vs the last figure stored in this file (often another website). Not 30-day Google growth.'
  }
  if (g.source === GMAPS_SOURCE) return 'First Google Maps copy in this file. 30/90/365-day growth unknown.'
  return 'No Google Maps copy yet. Period growth unknown.'
}

