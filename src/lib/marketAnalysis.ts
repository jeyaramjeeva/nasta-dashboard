export function isCoreIndian(v: Venue) {
  return !NOT_CORE_INDIAN.has(v.id)
}

export function listedOpen(city?: City) {
  return VENUES.filter((v) => {
    if (!isCoreIndian(v)) return false
    if (v.status !== 'Open') return false
    if (city && v.city !== city) return false
    return true
  })
}

export function densityPer10k(city: City) {
  const pop = city === 'Köln' ? MACRO.koelnPop.value : MACRO.bonnPop.value
  const n = listedOpen(city).length
  return { n, per10k: (n / pop) * 10_000, pop }
}

