function dump(name, obj, asConst = false) {
  const body = Object.entries(obj)
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
    .join('\n')
  return `const ${name} = {\n${body}\n}${asConst ? ' as const' : ''}\n`
}

const out = `export type Locale = 'en' | 'de' | 'ta' | 'ka'

${dump('en', en, true)}
export type I18nKey = keyof typeof en

${dump('de', de)}
${dump('ta', ta)}
${dump('ka', ka)}
const dict: Record<Locale, Record<I18nKey, string>> = { en, de, ta, ka }

export const LOCALES: Locale[] = ['en', 'de', 'ta', 'ka']

export const LOCALE_LABELS: Record<Locale, string> = {
  en: 'EN',
  de: 'DE',
  ta: 'TA',
  ka: 'KA',
}

export function t(locale: Locale, key: I18nKey): string {
  return dict[locale]?.[key] || en[key]
}

export function isLocale(v: string | null | undefined): v is Locale {
  return v === 'en' || v === 'de' || v === 'ta' || v === 'ka'
}

export function nextLocale(current: Locale): Locale {
  const i = LOCALES.indexOf(current)
  return LOCALES[(i + 1) % LOCALES.length]!
}
`

